#!/bin/bash
# Make glhello_gen.h from the output directory of VirtualIntelMac's
# scripts/generate-passthrough-opengl.py (run on the Mavericks 10.9 SDK).
# usage: gen-glhello-header.sh <generator-output-dir> <glhello_gen.h>
# Fails if DG_LAYOUT or the clear / clear_color opcodes are not found.
set -eu
dir=$1; out=$2
layout=$(sed -n 's/^#define DG_LAYOUT "\([0-9a-f]\{64\}\)"$/\1/p' "$dir/direct-layout.h")
clear=$(sed -n 's/^#define DG_OP_clear \([0-9][0-9]*\)u$/\1/p' "$dir/direct-opcodes.h")
color=$(sed -n 's/^#define DG_OP_clear_color \([0-9][0-9]*\)u$/\1/p' "$dir/direct-opcodes.h")
for v in layout clear color; do
  [ -n "${!v}" ] || { echo "::error::generated $v not found in $dir" >&2; exit 1; }
done
cat > "$out" <<H
/* Generated by gen-glhello-header.sh from VirtualIntelMac's
 * generate-passthrough-opengl.py output (Mavericks 10.9 SDK). Do not edit. */
#define GLH_LAYOUT "$layout"
#define GLH_OP_CLEAR $clear
#define GLH_OP_CLEAR_COLOR $color
H
cat "$out"
