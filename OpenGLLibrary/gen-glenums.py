#!/usr/bin/env python3
"""Write glenum-values.h: every numeric GL_ enum of the SDK's gl.h/glext.h as
a plain #define. Only names and numbers are taken from the headers (facts of
the OpenGL API); no header text is copied. The OS 9 library build uses it in
place of a GL header.

usage: gen-glenums.py <MacOSX10.9.sdk> <glenum-values.h>
CI only (the macOS codegen job has the SDK); never run on the maintainer's Mac.
"""
import pathlib
import re
import sys

sdk, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
headers = sdk / "System/Library/Frameworks/OpenGL.framework/Headers"
define = re.compile(r"^\s*#\s*define\s+(GL_[A-Za-z0-9_]+)\s+(.*)$")
literal = re.compile(r"^(0[xX][0-9a-fA-F]+|[0-9]+)[uUlL]*$")
values, aliases = {}, {}
for name in ("gl.h", "glext.h", "gl3.h", "gl3ext.h"):
    if not (headers / name).exists():
        continue
    text = re.sub(r"/\*.*?\*/", "", (headers / name).read_text(errors="replace"), flags=re.S)
    for line in text.splitlines():
        m = define.match(re.sub(r"//.*", "", line))
        if not m:
            continue
        key, rest = m.group(1), m.group(2).strip()
        if literal.match(rest):
            values[key] = int(re.match(r"0[xX][0-9a-fA-F]+|[0-9]+", rest).group(0), 0)
        elif re.match(r"^GL_[A-Za-z0-9_]+$", rest):
            aliases[key] = rest
for _ in range(8):
    for key, target in list(aliases.items()):
        if target in values:
            values[key] = values[target]
            del aliases[key]
lines = ["/* Generated by gen-glenums.py from the SDK's GL headers: names and numbers only. */"]
for key in sorted(values):
    v = values[key]
    lines.append("#define %s 0x%x%s" % (key, v, "u" if v > 0x7fffffff else ""))
out.write_text("\n".join(lines) + "\n")
print("glenum-values.h: %d enums, %d unresolved aliases" % (len(values), len(aliases)))
